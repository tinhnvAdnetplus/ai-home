import { z } from 'zod';

export const planInputSchema = z.object({
    frontage: z.number().finite().min(4).max(60),
    landDepth: z.number().finite().min(4).max(80),
    landAreaTsubo: z.number().finite().min(10).max(500),
    roadSide: z.enum(['北', '東', '南', '西']),
    landShape: z.enum(['正方形', '長方形', '変形']).optional(),
    surroundings: z.array(z.string().max(50)).max(20).optional(),
    adults: z.number().int().min(1).max(10).optional(),
    children: z.number().int().min(0).max(10).optional(),
    twoGen: z.string().max(50).optional(),
    futureFamily: z.string().max(50).optional(),
    targetArea: z.number().finite().min(15).max(150),
    floors: z.union([z.literal(1), z.literal(2)]),
    ldkSize: z.number().finite().min(10).max(40),
    masterSize: z.number().finite().min(4).max(20),
    kidsRooms: z.number().int().min(0).max(6),
    kidsSize: z.number().finite().min(3).max(15),
    roomTypes: z.array(z.string().max(50)).max(30).optional(),
    toilets: z.number().int().min(1).max(4),
    bathSize: z.enum(['1坪', '1.25坪', '1.5坪']),
    bathFloor: z.enum(['1階', '2階']),
    washCount: z.number().int().min(1).max(4),
    waterOpts: z.array(z.string().max(50)).max(20).optional(),
    tatamiRoom: z.string().max(50).optional(),
    storageLevel: z.string().max(50).optional(),
    wfh: z.string().max(50).optional(),
    exteriorStyle: z.string().max(50).optional(),
    roofType: z.string().max(50).optional(),
    interiorStyle: z.string().max(50).optional(),
    priorities: z.array(z.string().max(50)).max(20).optional(),
    mustHave: z.array(z.string().max(50)).max(20).optional(),
    notNeeded: z.array(z.string().max(50)).max(20).optional(),
    budget: z.number().finite().min(500).max(20000).optional(),
    budgetScope: z.string().max(50).optional(),
    cars: z.number().int().min(0).max(6),
    parkingType: z.string().max(50).optional(),
    evCharger: z.string().max(50).optional(),
    insulation: z.string().max(50).optional(),
    seismic: z.string().max(50).optional(),
    solar: z.string().max(50).optional(),
    coverageLimit: z.number().finite().min(20).max(100).optional(),
    floorRatioLimit: z.number().finite().min(50).max(500).optional(),
    masterCloset: z.string().max(50).optional(),
    kidsCloset: z.string().max(50).optional(),
    shoesCloset: z.string().max(50).optional(),
    storageOpts: z.array(z.string().max(50)).max(20).optional(),
    extraRooms: z.array(z.string().max(50)).max(20).optional(),
    outdoorOpts: z.array(z.string().max(50)).max(20).optional(),
    equipOpts: z.array(z.string().max(50)).max(20).optional(),
    kitchenType: z.string().max(50).optional(),
});
